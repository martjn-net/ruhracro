#!/usr/bin/env bash
# Build a self-contained upload folder for a sub-folder deployment.
# Usage: tools/bundle.sh <site-url> [--preview]
#   e.g. tools/bundle.sh https://martjn.net/acro --preview
# Result: dist/<folder>/ and dist/<folder>.zip. Upload the folder so that it
# becomes <docroot>/<folder>/ (docs/deploy.md). Layout:
#   <folder>/            web/public (index.php, .htaccess, assets/, img/, fonts/)
#   <folder>/_app/lib    web/lib + generated deploy.php   (denied by .htaccess)
#   <folder>/_app/pages  web/pages
# web/lib/provider.php (personal data) is never bundled; the placeholders of
# provider.example.php are used instead.
set -euo pipefail
cd "$(dirname "$0")/.."

url=${1:?usage: tools/bundle.sh <site-url> [--preview]}
url=${url%/}
preview=false
[[ "${2:-}" == "--preview" ]] && preview=true
folder=$(basename "$(php -r 'echo parse_url($argv[1], PHP_URL_PATH) ?? "";' "$url")")
[[ -n $folder && $folder != "/" ]] || { echo "site URL must end in a sub-folder, e.g. https://example.org/acro" >&2; exit 1; }
[[ -f web/public/img/head-6173.avif && -f web/public/fonts/kalam-700-latin.woff2 ]] \
  || { echo "images/fonts missing: run tools/build.sh first" >&2; exit 1; }

out=dist/$folder
rm -rf "$out" "$out.zip"
mkdir -p "$out/_app"
cp -a web/public/. "$out/"
cp -a web/lib web/pages "$out/_app/"
rm -f "$out/_app/lib/provider.php" "$out/_app/lib/deploy.php" "$out/_app/lib/deploy.example.php"
rm -f "$out/robots.txt" # crawlers only read /robots.txt at the domain root
printf '# Not web-accessible: application code.\nRequire all denied\n' > "$out/_app/.htaccess"
cat > "$out/_app/lib/deploy.php" <<PHP
<?php
// generated by tools/bundle.sh
return ['site_url' => '$url', 'preview' => $preview];
PHP

# the suite must pass with exactly this deployment config
ACRO_DEPLOY_CONFIG="$out/_app/lib/deploy.php" php web/tests/run_tests.php

(cd dist && zip -qr "$folder.zip" "$folder")
echo "bundle: $out ($(du -sh "$out" | cut -f1)), $out.zip"
